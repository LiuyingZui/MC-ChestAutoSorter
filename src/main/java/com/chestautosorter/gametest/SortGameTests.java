    private static Map<String, Long> tally(List<Container> containers) {
        Map<String, Long> m = new LinkedHashMap<>();
        for (Container c : containers) {
            for (int i = 0; i < c.getContainerSize(); i++) {
                ItemStack s = c.getItem(i);
                if (!s.isEmpty()) {
                    m.merge(id(s), (long) s.getCount(), Long::sum);
                }
            }
        }
        return m;
    }

