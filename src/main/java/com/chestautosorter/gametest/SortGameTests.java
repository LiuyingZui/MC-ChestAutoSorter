    /**
     * C: when mixed packing is disallowed and categories cannot each own a chest, the whole sort is
     * cancelled and every slot of the real containers is left byte-for-byte identical.
     */
    public static void mixedDisallowedCancelsAndLeavesChestsUntouched(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        BlockPos b = new BlockPos(3, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        helper.setBlock(b, Blocks.CHEST);
        List<Container> containers = containersOf(helper, a, b);
        Container ca = containers.get(0);
        Container cb = containers.get(1);

        // Three categories spread over two chests: dedicated layout is impossible.
        ca.setItem(0, new ItemStack(Items.OAK_LOG, 10));
        ca.setItem(1, new ItemStack(Items.STONE, 10));
        cb.setItem(0, new ItemStack(Items.IRON_INGOT, 10));
        cb.setItem(1, new ItemStack(Items.DIAMOND_SWORD, 1));
        ca.setChanged();
        cb.setChanged();

        List<ItemStack> beforeA = slots(ca);
        List<ItemStack> beforeB = slots(cb);

        List<ChestSnapshot> snaps = List.of(
                ChestSnapshot.of(helper.absolutePos(a), ca, false),
                ChestSnapshot.of(helper.absolutePos(b), cb, false));

        // allowMixed = false must cancel rather than fall back to mixed packing.
        SortPipelines.Plan plan = SortPipelines.plan(containers, snaps, false);
        if (!plan.isCancelled()) {
            helper.fail("expected cancellation with allowMixed=false, got " + plan.planner.status);
            return;
        }
        // Nothing may have been written by planning alone.
        assertSlotsEqual(helper, beforeA, slots(ca), "chest A after cancelled plan");
        assertSlotsEqual(helper, beforeB, slots(cb), "chest B after cancelled plan");

        // The same inventory with mixed allowed and capacity available must succeed.
        SortPipelines.Plan ok = SortPipelines.plan(containers, snaps, true);
        if (ok.isCancelled()) {
            helper.fail("mixed layout should fit but was cancelled: " + ok.messages());
            return;
        }
        helper.succeed();
    }

    /**
     * D2: the read-back after writing disagrees because a stacked count was silently truncated.
     * The committer must detect this, roll back, and the real containers must equal the original.
     * Distinct from the thrown-exception case: nothing here throws during writing.
     */
    public static void commitRollsBackOnReadbackMismatch(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        BlockPos b = new BlockPos(3, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        helper.setBlock(b, Blocks.CHEST);
        List<Container> containers = containersOf(helper, a, b);
        Container ca = containers.get(0);
        Container cb = containers.get(1);

        // Items deliberately in the "wrong" chests so the committed layout must move them.
        ca.setItem(0, new ItemStack(Items.IRON_INGOT, 20));
        ca.setItem(1, new ItemStack(Items.OAK_LOG, 40));
        cb.setItem(0, new ItemStack(Items.STONE, 25));
        ca.setChanged();
        cb.setChanged();

        List<ChestSnapshot> snaps = List.of(
                ChestSnapshot.of(helper.absolutePos(a), ca, false),
                ChestSnapshot.of(helper.absolutePos(b), cb, false));
        SortPipelines.Plan plan = SortPipelines.plan(containers, snaps, true);
        if (plan.isCancelled()) {
            helper.fail("unexpected cancellation");
            return;
        }

        // Find a slot the plan actually rewrites with different content; tampering anywhere else
        // would leave the read-back matching the plan and prove nothing.
        com.chestautosorter.server.PlannedStacks.begin();
        SafeCommitter.BlockPosKey[] target = {null};
        int targetSlot = -1;
        boolean found = false;
        try {
            for (ChestSnapshot snap : snaps) {
                for (int i = 0; i < snap.size; i++) {
                    ItemStack s = snap.slots.get(i);
                    if (!s.isEmpty()) {
                        com.chestautosorter.server.PlannedStacks.put(com.chestautosorter.core.McStackKey.of(s), s);
                    }
                }
            }
            for (com.chestautosorter.core.SortPlanner.SlotPlan p : plan.planner.layout) {
                if (p.isEmpty()) {
                    continue;
                }
                Container c = containers.get(p.container);
                ItemStack orig = c.getItem(p.slot);
                ItemStack planned = com.chestautosorter.server.PlannedStacks.materialize(p.entry);
                if (!ItemStack.matches(orig, planned)) {
                    target[0] = p.container == 0 ? key(helper, a) : key(helper, b);
                    targetSlot = p.slot;
                    found = true;
                    break;
                }
            }
        } finally {
            com.chestautosorter.server.PlannedStacks.end();
        }
        if (!found) {
            helper.fail("test setup is vacuous: the plan rewrites no slot with different content");
            return;
        }
        final boolean[] swapped = {false};
        final String[] swapInfo = {""};
        List<ItemStack> expectedA = slots(ca);
        List<ItemStack> expectedB = slots(cb);

        // Tamper AFTER writing, BEFORE verification. The tamper must preserve global totals (so the
        // conservation check cannot catch it) while breaking the slot layout, so that only the
        // layout read-back can detect it. Swapping two filled slots achieves exactly that.
        SafeCommitter.setHooks(new SafeCommitter.Hooks() {
            @Override
            public void afterWrites() {
                try {
                    for (Container c : containers) {
                        List<Integer> filled = new ArrayList<>();
                        for (int i = 0; i < c.getContainerSize(); i++) {
                            if (!c.getItem(i).isEmpty()) {
                                filled.add(i);
                            }
                        }
                        if (filled.size() >= 2) {
                            int i0 = filled.get(0);
                            int i1 = filled.get(1);
                            ItemStack a0 = c.getItem(i0).copy();
                            ItemStack a1 = c.getItem(i1).copy();
                            c.setItem(i0, a1);
                            c.setItem(i1, a0);
                            swapped[0] = true;
                            swapInfo[0] = "swapped slots " + i0 + " and " + i1;
                            return;
                        }
                    }
                    swapInfo[0] = "no container had two filled slots: A=" + dump(ca) + " B=" + dump(cb);
                } catch (Throwable t) {
                    swapInfo[0] = "tamper threw: " + t;
                }
            }
        });
        SafeCommitter.Prepared prepared = SafeCommitter.prepare(containers, List.of(key(helper, a), key(helper, b)));
        com.chestautosorter.server.PlannedStacks.begin();
        SafeCommitter.Outcome outcome;
        try {
            for (ChestSnapshot snap : snaps) {
                for (int i = 0; i < snap.size; i++) {
                    ItemStack s = snap.slots.get(i);
                    if (!s.isEmpty()) {
                        com.chestautosorter.server.PlannedStacks.put(com.chestautosorter.core.McStackKey.of(s), s);
                    }
                }
            }
            outcome = SafeCommitter.commit(prepared, plan.planner.layout);
        } finally {
            SafeCommitter.clearHooks();
            com.chestautosorter.server.PlannedStacks.end();
        }

        if (!swapped[0]) {
            helper.fail("test setup is vacuous: could not swap two filled slots. " + swapInfo[0]);
            return;
        }
        if (outcome.success) {
            helper.fail("commit reported success despite a read-back layout mismatch"
                    + " (totals unchanged, so only the layout check can catch this)");
            return;
        }
        if (!outcome.rolledBack || !outcome.rollbackVerified) {
            helper.fail("expected verified rollback, got rolledBack=" + outcome.rolledBack
                    + " rollbackVerified=" + outcome.rollbackVerified);
            return;
        }
        assertSlotsEqual(helper, expectedA, slots(ca), "chest A after read-back rollback");
        assertSlotsEqual(helper, expectedB, slots(cb), "chest B after read-back rollback");
        helper.succeed();
    }

    /**
     * E: rollback itself fails. The committer must NOT report success or a verified rollback, and the
     * original pre-image must still be available for diagnosis.
     */
    public static void commitReportsFailureWhenRollbackAlsoFails(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        BlockPos b = new BlockPos(3, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        helper.setBlock(b, Blocks.CHEST);
        List<Container> containers = containersOf(helper, a, b);
        Container ca = containers.get(0);
        Container cb = containers.get(1);

        ca.setItem(0, new ItemStack(Items.IRON_INGOT, 20));
        ca.setItem(1, new ItemStack(Items.OAK_LOG, 40));
        cb.setItem(0, new ItemStack(Items.STONE, 25));
        ca.setChanged();
        cb.setChanged();

        List<ChestSnapshot> snaps = List.of(
                ChestSnapshot.of(helper.absolutePos(a), ca, false),
                ChestSnapshot.of(helper.absolutePos(b), cb, false));
        SortPipelines.Plan plan = SortPipelines.plan(containers, snaps, true);
        if (plan.isCancelled()) {
            helper.fail("unexpected cancellation");
            return;
        }
        List<ItemStack> preImage = slots(ca);
        final int layoutSize = plan.planner.layout.size();

        // Fail on the first write, then also fail every restore attempt, so the rollback cannot
        // complete. Nothing may be reported as success or as a verified rollback.
        final boolean[] writeFailed = {false};
        final int[] restoreAttempts = {0};
        SafeCommitter.setHooks(new SafeCommitter.Hooks() {
            @Override
            public void beforeWrite(Container container, int slot, ItemStack incoming) {
                if (!writeFailed[0]) {
                    writeFailed[0] = true;
                    throw new RuntimeException("injected write failure");
                }
            }

            @Override
            public void beforeRestore(Container container, int slot) {
                restoreAttempts[0]++;
                throw new RuntimeException("injected restore failure");
            }
        });
        SafeCommitter.Prepared prepared = SafeCommitter.prepare(containers, List.of(key(helper, a), key(helper, b)));
        com.chestautosorter.server.PlannedStacks.begin();
        SafeCommitter.Outcome outcome;
        try {
            for (ChestSnapshot snap : snaps) {
                for (int i = 0; i < snap.size; i++) {
                    ItemStack s = snap.slots.get(i);
                    if (!s.isEmpty()) {
                        com.chestautosorter.server.PlannedStacks.put(com.chestautosorter.core.McStackKey.of(s), s);
                    }
                }
            }
            outcome = SafeCommitter.commit(prepared, plan.planner.layout);
        } finally {
            SafeCommitter.clearHooks();
            com.chestautosorter.server.PlannedStacks.end();
        }

        if (!writeFailed[0]) {
            helper.fail("test setup is vacuous: the write failure never fired (" + layoutSize + " layout slots)");
            return;
        }
        if (restoreAttempts[0] == 0) {
            helper.fail("test setup is vacuous: restore was never attempted");
            return;
        }
        if (outcome.success) {
            helper.fail("commit reported SUCCESS while restoration failed");
            return;
        }
        if (outcome.rollbackVerified) {
            helper.fail("commit reported a VERIFIED rollback even though restore() kept failing");
            return;
        }
        if (!outcome.rolledBack) {
            helper.fail("commit should report that a rollback was attempted");
            return;
        }
        // The pre-image must remain readable for diagnosis regardless of the outcome.
        if (preImage.isEmpty() || preImage.get(0).isEmpty()) {
            helper.fail("pre-image was lost; nothing left for recovery");
            return;
        }
        helper.succeed();
    }

