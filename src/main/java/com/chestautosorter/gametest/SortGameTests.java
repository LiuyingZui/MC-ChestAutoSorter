    /**
     * Drives the real server-side validation ({@code SortService.validate}, the same method
     * {@code onRequest} calls) at the acceptance distances, and checks that range is measured from
     * the eye to the logical container bounds with a {@code <= radius} boundary.
     *
     * <p>The player stands at a fixed height and is moved along +X, so the horizontal gap to the
     * chest's block box is exactly the requested distance and eye height does not enter into it.
     */
    public static void range_rule_uses_eye_to_logical_bounds(GameTestHelper helper) {
        BlockPos chest = new BlockPos(1, 1, 1);
        helper.setBlock(chest, Blocks.CHEST);
        net.minecraft.world.entity.player.Player player = helper.makeMockServerPlayer(net.minecraft.world.level.GameType.SURVIVAL);

        int radius = 12;
        double[] inRange = {6.0, 10.0, 11.5, 12.0};
        for (double gap : inRange) {
            placeAt(player, helper, chest, gap);
            List<String> skipped = new ArrayList<>();
            var accepted = com.chestautosorter.server.SortService.validate(
                    (net.minecraft.server.level.ServerPlayer) player, List.of(helper.absolutePos(chest)), radius, skipped);
            if (accepted.isEmpty()) {
                helper.fail("gap " + gap + " should be accepted but was skipped: " + skipped);
                return;
            }
        }

        double outOfRange = 12.5;
        placeAt(player, helper, chest, outOfRange);
        List<String> skipped = new ArrayList<>();
        var accepted = com.chestautosorter.server.SortService.validate(
                (net.minecraft.server.level.ServerPlayer) player, List.of(helper.absolutePos(chest)), radius, skipped);
        if (!accepted.isEmpty()) {
            helper.fail("gap " + outOfRange + " should be rejected but was accepted");
            return;
        }
        // The server ships translation keys, not rendered text, so the assertion targets the key.
        boolean reasonIsRange = skipped.stream().anyMatch(s -> s.contains("chestautosorter.reason.too_far"));
        if (!reasonIsRange) {
            helper.fail("out-of-range rejection should carry key chestautosorter.reason.too_far, was: " + skipped);
            return;
        }
        helper.succeed();
    }

    /** Places the player {@code gap} blocks along +X from the chest, keeping a constant eye height. */
    private static void placeAt(net.minecraft.world.entity.player.Player player, GameTestHelper helper,
                                BlockPos chest, double gap) {
        BlockPos abs = helper.absolutePos(chest);
        player.setPos(abs.getX() + 0.5 + gap, abs.getY() + 0.5, abs.getZ() + 0.5);
    }
