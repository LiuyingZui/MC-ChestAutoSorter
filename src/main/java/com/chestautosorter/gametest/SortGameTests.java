    /**
     * Three single chests, each pre-mixed with wood / stone / ore, are redistributed across boxes by
     * category. Asserts cross-chest movement, per-slot counts, full component data, and that a fourth
     * (non-participating) chest is untouched.
     */
    public static void mixedChestsAreRedistributedByCategory(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        BlockPos b = new BlockPos(3, 1, 1);
        BlockPos c = new BlockPos(5, 1, 1);
        BlockPos bystander = new BlockPos(7, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        helper.setBlock(b, Blocks.CHEST);
        helper.setBlock(c, Blocks.CHEST);
        helper.setBlock(bystander, Blocks.CHEST);

        List<Container> boxes = containersOf(helper, a, b, c);
        Container ca = boxes.get(0);
        Container cb = boxes.get(1);
        Container cc = boxes.get(2);
        Container cbystander = containersOf(helper, bystander).get(0);

        // Deliberately wrong boxes: every chest holds a mix of all three categories.
        // WOOD
        fill(ca, 0, new ItemStack(Items.OAK_LOG, 30));
        fill(cb, 0, new ItemStack(Items.OAK_PLANKS, 12));
        fill(cc, 0, new ItemStack(Items.OAK_LOG, 10));
        // STONE
        fill(ca, 1, new ItemStack(Items.STONE, 40));
        fill(cb, 1, new ItemStack(Items.COBBLESTONE, 20));
        fill(cc, 1, new ItemStack(Items.STONE, 5));
        // ORE
        fill(ca, 2, new ItemStack(Items.IRON_INGOT, 25));
        fill(cb, 2, new ItemStack(Items.GOLD_INGOT, 15));
        fill(cc, 2, new ItemStack(Items.DIAMOND, 3));

        // The bystander must never be touched.
        fill(cbystander, 0, new ItemStack(Items.APPLE, 9));

        ItemStack bystanderBefore = cbystander.getItem(0).copy();

        List<Container> participating = List.of(ca, cb, cc);
        Map<String, Long> before = tally(participating);
        // Explicit expectations (not generated by the code under test).
        assertEquals(helper, 40L, before.get("minecraft:oak_log"), "oak_log before");
        assertEquals(helper, 12L, before.get("minecraft:oak_planks"), "oak_planks before");
        assertEquals(helper, 45L, before.get("minecraft:stone"), "stone before");
        assertEquals(helper, 20L, before.get("minecraft:cobblestone"), "cobblestone before");
        assertEquals(helper, 25L, before.get("minecraft:iron_ingot"), "iron before");
        assertEquals(helper, 15L, before.get("minecraft:gold_ingot"), "gold before");
        assertEquals(helper, 3L, before.get("minecraft:diamond"), "diamond before");

        List<ChestSnapshot> snaps = new ArrayList<>();
        snaps.add(ChestSnapshot.of(helper.absolutePos(a), ca, false));
        snaps.add(ChestSnapshot.of(helper.absolutePos(b), cb, false));
        snaps.add(ChestSnapshot.of(helper.absolutePos(c), cc, false));

        // --- run the PRODUCTION pipeline ---
        SortPipelines.Outcome outcome = SortPipelines.runProduction(participating, snaps, true);
        if (!outcome.success) {
            helper.fail("pipeline failed: " + outcome.message);
            return;
        }

        // --- 1. conservation on real containers, per identity ---
        Map<String, Long> after = tally(participating);
        if (!before.equals(after)) {
            helper.fail("conservation broken: before=" + before + " after=" + after);
            return;
        }

        // --- 2. the layout really is category-dedicated and cross-chest ---
        for (int i = 0; i < participating.size(); i++) {
            Category expected = switch (i) {
                case 0 -> Category.WOOD;
                case 1 -> Category.STONE_BUILDING;
                default -> Category.ORE;
            };
            Category actual = dominantCategory(participating.get(i));
            if (actual != null && actual != expected) {
                helper.fail("box" + i + " holds " + actual + " but expected " + expected);
                return;
            }
        }

        // Box 0 originally mixed all three categories and must no longer do so.
        if (distinctCategories(ca) >= 3) {
            StringBuilder cls = new StringBuilder();
            for (int i = 0; i < ca.getContainerSize(); i++) {
                ItemStack s = ca.getItem(i);
                if (!s.isEmpty()) {
                    cls.append(id(s)).append('=')
                            .append(catOf(s)).append(' ');
                }
            }
            helper.fail("box0 still mixes all three categories; no cross-chest redistribution happened"
                    + " | box0=" + dump(ca) + " box1=" + dump(cb) + " box2=" + dump(cc)
                    + " | status=" + outcome.plan.status + " msgs=" + outcome.plan.messages
                    + " | classified: " + cls);
            return;
        }
        // Cross-chest proof: ores started spread over boxes 0/1/2; after a dedicated layout every ore
        // must sit in a single box, so at least two of the three original boxes lost their ore.
        int oreBoxes = 0;
        for (Container box : participating) {
            if (containerHasItem(box, Items.IRON_INGOT) || containerHasItem(box, Items.GOLD_INGOT)
                    || containerHasItem(box, Items.DIAMOND)) {
                oreBoxes++;
            }
        }
        if (oreBoxes != 1) {
            helper.fail("expected all ores consolidated into exactly 1 box, found " + oreBoxes);
            return;
        }

        // --- 4. bystander untouched ---
        ItemStack bystanderAfter = cbystander.getItem(0);
        if (!ItemStack.matches(bystanderBefore, bystanderAfter)) {
            helper.fail("non-participating chest was modified");
            return;
        }

        helper.succeed();
    }

    /** A properly-formed double chest must resolve as one 54-slot logical container. */
    public static void doubleChestIsOneContainer(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        // Two chests only merge when their TYPE states point at each other, which vanilla normally
        // establishes through updateShape when a player places the second half. setBlock bypasses
        // that, so the states must be written explicitly.
        // With FACING=NORTH, getConnectedDirection is EAST for LEFT and WEST for RIGHT, so the LEFT
        // half must sit at the lower x and the RIGHT half at the higher x.
        helper.setBlock(a, Blocks.CHEST.defaultBlockState()
                .setValue(ChestBlock.FACING, Direction.NORTH)
                .setValue(ChestBlock.TYPE, ChestType.LEFT));
        helper.setBlock(new BlockPos(2, 1, 1), Blocks.CHEST.defaultBlockState()
                .setValue(ChestBlock.FACING, Direction.NORTH)
                .setValue(ChestBlock.TYPE, ChestType.RIGHT));

        Container whole = SupportedChests.resolve(helper.getLevel(), helper.absolutePos(a));
        if (whole == null || whole.getContainerSize() != 54) {
            helper.fail("double chest size wrong: " + (whole == null ? "null" : whole.getContainerSize()));
            return;
        }
        for (int i = 0; i < 54; i++) {
            whole.setItem(i, new ItemStack(Items.COBBLESTONE, 64));
        }
        whole.setChanged();
        if (count(whole, Items.COBBLESTONE) != 54L * 64L) {
            helper.fail("double chest contents wrong");
            return;
        }
        helper.succeed();
    }

    /** After a successful commit, item identities and counts are conserved, including components. */
    public static void commitConservesComponents(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        Container ca = SupportedChests.resolve(helper.getLevel(), helper.absolutePos(a));
        if (ca == null) {
            helper.fail("no container");
            return;
        }
        ItemStack named = new ItemStack(Items.DIAMOND_SWORD);
        named.set(DataComponents.CUSTOM_NAME, Component.literal("Test Sword"));
        ca.setItem(0, named);
        ca.setItem(1, new ItemStack(Items.DIAMOND_SWORD));
        ca.setItem(2, new ItemStack(Items.OAK_LOG, 64));
        ca.setChanged();

        List<Container> containers = List.of(ca);
        List<ChestSnapshot> snaps = List.of(ChestSnapshot.of(helper.absolutePos(a), ca, false));
        SortPipelines.Outcome outcome = SortPipelines.runProduction(containers, snaps, true);
        if (!outcome.success) {
            helper.fail("pipeline failed: " + outcome.message);
            return;
        }
        boolean hasNamed = false;
        boolean hasPlain = false;
        for (int i = 0; i < ca.getContainerSize(); i++) {
            ItemStack s = ca.getItem(i);
            if (!s.isEmpty() && s.is(Items.DIAMOND_SWORD)) {
                if (s.get(DataComponents.CUSTOM_NAME) != null) {
                    hasNamed = true;
                } else {
                    hasPlain = true;
                }
            }
        }
        if (!hasNamed || !hasPlain) {
            helper.fail("component identity lost: named=" + hasNamed + " plain=" + hasPlain);
            return;
        }
        helper.succeed();
    }

    /**
     * B: the inventory changes between snapshot and write. The commit must refuse and must NOT write,
     * and in particular must not clobber the fresh change with the stale snapshot.
     */
    public static void commitRejectsWhenInventoryChanged(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        Container ca = SupportedChests.resolve(helper.getLevel(), helper.absolutePos(a));
        if (ca == null) {
            helper.fail("no container");
            return;
        }
        ca.setItem(0, new ItemStack(Items.OAK_LOG, 10));
        ca.setItem(1, new ItemStack(Items.IRON_INGOT, 10));
        ca.setChanged();

        List<Container> containers = List.of(ca);
        List<ChestSnapshot> snaps = List.of(ChestSnapshot.of(helper.absolutePos(a), ca, false));
        SafeCommitter.Prepared prepared = SafeCommitter.prepare(containers, List.of(key(helper, a)));

        // Simulate another actor changing the chest AFTER the snapshot was taken.
        ItemStack intruder = new ItemStack(Items.DIAMOND, 7);
        ca.setItem(0, intruder);

        List<com.chestautosorter.core.StackEntry> entries = SortPipelines.entries(snaps, containers);
        var plan = com.chestautosorter.core.SortPlanner.plan(List.of(snaps.get(0).size),
                com.chestautosorter.core.StackAggregator.aggregate(entries), true);
        if (plan.isCancelled()) {
            helper.fail("unexpected planner cancellation");
            return;
        }
        SafeCommitter.Outcome outcome = SafeCommitter.commit(prepared, plan.layout);

        if (outcome.success) {
            helper.fail("commit succeeded despite inventory change");
            return;
        }
        // The fresh change must survive untouched; the stale snapshot must NOT be restored over it.
        if (!ItemStack.matches(intruder, ca.getItem(0))) {
            helper.fail("stale snapshot was restored over the new change: " + ca.getItem(0));
            return;
        }
        if (!ca.getItem(1).is(Items.IRON_INGOT) || ca.getItem(1).getCount() != 10) {
            helper.fail("slot1 was modified: " + ca.getItem(1));
            return;
        }
        helper.succeed();
    }

    /**
     * D: a write fails partway through. The already-modified slots must be restored to the exact
     * pre-commit state (verified by reading the real containers), not merely reported as rolled back.
     */
    public static void commitRollsBackOnPartialWriteFailure(GameTestHelper helper) {
        BlockPos a = new BlockPos(1, 1, 1);
        BlockPos b = new BlockPos(3, 1, 1);
        helper.setBlock(a, Blocks.CHEST);
        helper.setBlock(b, Blocks.CHEST);
        List<Container> containers = containersOf(helper, a, b);
        Container ca = containers.get(0);
        Container cb = containers.get(1);

        ca.setItem(0, new ItemStack(Items.OAK_LOG, 30));
        ca.setItem(1, new ItemStack(Items.STONE, 20));
        cb.setItem(0, new ItemStack(Items.IRON_INGOT, 15));
        cb.setItem(1, new ItemStack(Items.GOLD_INGOT, 5));
        ca.setChanged();
        cb.setChanged();

        List<ChestSnapshot> snaps = List.of(
                ChestSnapshot.of(helper.absolutePos(a), ca, false),
                ChestSnapshot.of(helper.absolutePos(b), cb, false));
        List<com.chestautosorter.core.StackEntry> entries = SortPipelines.entries(snaps, containers);
        // The committer materializes stacks from prototypes keyed by identity, exactly as the
        // production pipeline does; this test drives commit() directly, so seed them here.
        com.chestautosorter.server.PlannedStacks.begin();
        var plan = com.chestautosorter.core.SortPlanner.plan(
                List.of(snaps.get(0).size, snaps.get(1).size),
                com.chestautosorter.core.StackAggregator.aggregate(entries), true);
        if (plan.isCancelled()) {
            com.chestautosorter.server.PlannedStacks.end();
            helper.fail("unexpected planner cancellation");
            return;
        }
        for (ChestSnapshot snap : snaps) {
            for (int i = 0; i < snap.size; i++) {
                ItemStack s = snap.slots.get(i);
                if (!s.isEmpty()) {
                    com.chestautosorter.server.PlannedStacks.put(com.chestautosorter.core.McStackKey.of(s), s);
                }
            }
        }

        SafeCommitter.Prepared prepared = SafeCommitter.prepare(containers, List.of(key(helper, a), key(helper, b)));
        // Snapshot the true pre-commit state, read from the real containers.
        List<ItemStack> expectedA = slots(ca);
        List<ItemStack> expectedB = slots(cb);

        // Inject a failure only AFTER at least one slot has been overwritten with content that
        // differs from the original. Failing earlier would leave the containers untouched, and the
        // slot-by-slot comparison below would then pass even if rollback were a no-op.
        // The hook runs before the write, so divergence is detected by asking the committer which
        // stack it is about to place, and comparing that against the original slot contents.
        final boolean[] diverged = {false};
        final int[] writes = {0};
        SafeCommitter.setHooks(new SafeCommitter.Hooks() {
            @Override
            public void beforeWrite(Container container, int slot, ItemStack incoming) {
                int idx = container == ca ? slot : (container == cb ? slot : -1);
                List<ItemStack> orig = container == ca ? expectedA : expectedB;
                if (idx >= 0 && idx < orig.size()) {
                    if (diverged[0]) {
                        throw new RuntimeException("injected write failure after real divergence");
                    }
                    if (!ItemStack.matches(incoming, orig.get(idx))) {
                        diverged[0] = true;
                    }
                }
                writes[0]++;
            }
        });
        SafeCommitter.Outcome outcome;
        try {
            outcome = SafeCommitter.commit(prepared, plan.layout);
        } finally {
            SafeCommitter.clearHooks();
            com.chestautosorter.server.PlannedStacks.end();
        }

        // Guard against a vacuous test: the injection must have fired on a genuinely changed slot.
        if (!diverged[0]) {
            helper.fail("test setup is vacuous: no slot was overwritten with different content before"
                    + " the injected failure (" + writes[0] + " writes); plan=" + planDesc(plan)
                    + " expectedA=" + dumpList(expectedA) + " expectedB=" + dumpList(expectedB));
            return;
        }
        if (outcome.success) {
            helper.fail("commit reported success despite injected failure");
            return;
        }
        if (!outcome.rolledBack) {
            helper.fail("commit did not roll back");
            return;
        }
        if (!outcome.rollbackVerified) {
            helper.fail("rollback verification failed");
            return;
        }
        // Read the REAL containers and compare slot-by-slot, including full item data.
        assertSlotsEqual(helper, expectedA, slots(ca), "chest A after rollback");
        assertSlotsEqual(helper, expectedB, slots(cb), "chest B after rollback");
        helper.succeed();
    }

