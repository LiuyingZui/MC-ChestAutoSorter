    // --- container helpers -------------------------------------------------------------------

    /** Minimal production-equivalent view: read a slot, write a slot, know the slot count. */
    static List<Container> containersOf(GameTestHelper helper, BlockPos... positions) {
        List<Container> out = new ArrayList<>();
        for (BlockPos p : positions) {
            Container c = SupportedChests.resolve(helper.getLevel(), helper.absolutePos(p));
            if (c == null) {
                throw new IllegalStateException("unresolved container at " + p);
            }
            out.add(c);
        }
        return out;
    }

    static void fill(Container c, int slot, ItemStack stack) {
        c.setItem(slot, stack);
    }

